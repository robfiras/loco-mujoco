def table(header: List[str], rows: List[List[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def class_ref(cls: type) -> str:
    return f"{{class}}`~{cls.__module__}.{cls.__qualname__}`"


def hz(timestep: float, n_substeps: int) -> str:
    return fmt(1.0 / (timestep * n_substeps))


def ms(timestep: float) -> str:
    return fmt(timestep * 1000.0)


def datasets_text(e: Embodiment) -> str:
    return ", ".join(DATASET_LABELS[d] for d in e.datasets) if e.datasets else "none"


def existing_images(e: Embodiment) -> List[str]:
    return [img for img in e.meta["images"] if (IMG_DIR / img).is_file()]


def quick_start(e: Embodiment) -> str:
    """The quick-start snippet: imitation with the default dataset if there is data, plain RL otherwise."""
    def snippet(name: str, mjx: bool) -> str:
        if e.datasets:
            lines = ["from loco_mujoco.task_factories import ImitationFactory, DefaultDatasetConf",
                     "",
                     f'env, traj = ImitationFactory.make("{name}",',
                     '                                  default_dataset_conf=DefaultDatasetConf(task="walk"))']
        else:
            lines = ["from loco_mujoco.task_factories import RLFactory",
                     "",
                     f'env, _ = RLFactory.make("{name}")']
        if mjx:
            lines = ["import jax", ""] + lines
            traj = "traj" if e.datasets else "None"
            lines += ["",
                      "n_envs = 1024",
                      "reset = jax.jit(jax.vmap(env.mjx_reset, in_axes=(0, None)))",
                      "step = jax.jit(jax.vmap(env.mjx_step, in_axes=(0, 0, None)))",
                      "",
                      "keys = jax.random.split(jax.random.key(0), n_envs)",
                      f"state = reset(keys, {traj})",
                      "action = jax.vmap(env.sample_action_space)(keys)",
                      f"state = step(state, action, {traj})"]
        elif e.datasets:
            lines += ["",
                      "# replay the reference motion",
                      "env.play_trajectory(n_episodes=3, n_steps_per_episode=500, render=True)"]
        else:
            lines += ["",
                      "import numpy as np",
                      "",
                      "env.reset()",
                      "for _ in range(1000):",
                      "    action = np.random.uniform(-1.0, 1.0, env.info.action_space.shape)",
                      "    obs, reward, absorbing, done, info = env.step(action)",
                      "    env.render()"]
        return "```python\n" + "\n".join(lines) + "\n```"

    if not e.mjx_name:
        return snippet(e.name, False)
    return "\n".join([
        "`````{tab-set}",
        "````{tab-item} MuJoCo (CPU)",
        snippet(e.name, False),
        "````",
        "````{tab-item} MJX (GPU)",
        snippet(e.mjx_name, True),
        "````",
        "`````"])


def render_page(e: Embodiment) -> str:
    m, f = e.meta, e.facts
    out = [HEADER, f"# {m['title']}", ""]

    images = existing_images(e)
    if len(images) >= 2:
        out += ["::::{grid} 2", ":gutter: 2", ""]
        for img in images[:2]:
            out += [":::{grid-item}", f"```{{image}} {IMG_REL}/{img}", f":alt: The {m['title']} environment",
                    ":width: 100%", "```", ":::", ""]
        out += ["::::", ""]
    elif images:
        out += [f"```{{image}} {IMG_REL}/{images[0]}", f":alt: The {m['title']} environment", ":width: 60%",
                ":align: center", "```", ""]

    out += [m["description"], ""]

    out += ["## Quick start", ""]
    if e.datasets:
        out += [f"The registered name of this environment is `{e.name}`. The snippet loads the walking clip of "
                "the default dataset, which is downloaded on first use. LAFAN1 and AMASS clips are loaded the "
                "same way, see [datasets](../user_guide/datasets.md).", ""]
    else:
        out += [f"The registered name of this environment is `{e.name}`. There is no motion capture data for "
                "it, so it is created with "
                "{class}`~loco_mujoco.task_factories.rl_factory.RLFactory`, whose default task is to track a "
                "commanded root velocity.", ""]
    out += [quick_start(e), ""]
    if e.name == "MyoSkeleton":
        out += ["```{note}", "The MyoSkeleton model has to be downloaded once with `loco-mujoco-myomodel-init`, "
                "which asks you to accept its license. See [installation](../getting_started/installation.md).",
                "```", ""]

    if e.error:
        out += ["## Facts", "",
                "```{warning}",
                f"This environment could not be instantiated when the page was generated ({e.error}), so the "
                "facts and the tables of the observation and action space are missing. Run "
                "`python docs/_scripts/generate_environments.py` on a machine where the model is installed to "
                "fill them in.",
                "```", ""]
        rows = [["Registered name", f"`{e.name}`"],
                ["MJX variant", f"`{e.mjx_name}`" if e.mjx_name else "none"],
                ["Type", GROUPS[e.group]["type_label"]],
                ["Motion capture data", datasets_text(e)]]
        out += [table(["Property", "Value"], rows), ""]
    else:
        if len(f["kind_counts"]) == 1:
            kinds = next(iter(f["kind_counts"]))
        else:
            kinds = ", ".join(f"{n} {k}" for k, n in f["kind_counts"].items())
        rows = [
            ["Registered name", f"`{e.name}`"],
            ["MJX variant", f"`{e.mjx_name}`" if e.mjx_name else "none"],
            ["Type", GROUPS[e.group]["type_label"]],
            ["Joints (without the floating base)", f["n_joints"]],
            ["Degrees of freedom (without the floating base)", f["n_dof"]],
            ["Size of `qpos` / `qvel`", f"{f['nq']} / {f['nv']}"],
            ["Actuators", f"{f['n_actuators']} ({kinds})"],
            ["Action dimension", f["action_dim"]],
            ["Default control type", class_ref(f["control_cls"])],
            ["Observation dimension", f["obs_dim"]],
            ["Simulation time step (MuJoCo)", f"{ms(f['timestep'])} ms, {f['n_substeps']} substeps per step"],
            ["Control frequency (MuJoCo)", f"{hz(f['timestep'], f['n_substeps'])} Hz"],
        ]
        if e.mjx_timing:
            ts, ns = e.mjx_timing
            rows += [["Simulation time step (MJX)", f"{ms(ts)} ms, {ns} substeps per step"],
                     ["Control frequency (MJX)", f"{hz(ts, ns)} Hz"]]
        if f["n_eq"]:
            rows += [["Equality constraints", f["n_eq"]]]
        if f["n_mimic_sites"]:
            rows += [["Mimic sites", f["n_mimic_sites"]]]
        rows += [["Motion capture data", datasets_text(e)],
                 ["Model file", f"`{f['model_file']}`"]]
        out += ["## Facts", "",
                "The numbers describe the environment as it is created with its default arguments.", "",
                table(["Property", "Value"], rows), ""]
        if e.aliases:
            names = " and ".join(f"`{a}`" for a in e.aliases)
            out += [f"{names} {'is a deprecated alias' if len(e.aliases) == 1 else 'are deprecated aliases'} of "
                    f"this environment and will be removed in a future release.", ""]

    out += ["## Constructor options", ""]
    if e.options:
        out += ["These keyword arguments are specific to this embodiment. They can be passed to the constructor "
                "or to a [task factory](../user_guide/task_factories.md), which forwards them.", ""]
        has_effect = any(o.effect for o in e.options)
        header = ["Argument", "Default", "Description"] + (["Effect of the other value"] if has_effect else [])
        rows = [[f"`{o.name}`", f"`{o.default}`", o.description] + ([o.effect] if has_effect else [])
                for o in e.options]
        out += [table(header, rows), ""]
    else:
        out += ["This embodiment has no arguments of its own.", ""]
    out += ["All environments also accept `spec`, `observation_spec` and `actuation_spec` to replace the model, "
            "the observation space and the set of actuators, and the arguments of "
            "{class}`~loco_mujoco.environments.base.LocoEnv` and {class}`~loco_mujoco.core.mujoco_base.Mujoco`, "
            "such as `timestep`, `n_substeps`, `reward_type`, `control_type` or `terrain_type`. See the "
            "[modular architecture](../user_guide/modular_architecture.md).", ""]

    if not e.error:
        out += ["## Observation space", "",
                f"The default observation has {f['obs_dim']} dimensions: the pose of the floating base without "
                "its horizontal position, the joint positions, the velocity of the floating base and the joint "
                "velocities. A task factory may append further entries; "
                "{class}`~loco_mujoco.task_factories.rl_factory.RLFactory`, for example, adds the velocity "
                "goal. See [observations](../user_guide/observations.md) for how to change the observation "
                "space.", "",
                table(["Index", "Name", "Observation type", "Dim", "Model element"],
                      [[idx, f"`{name}`", class_ref(cls), dim, f"`{xml}`" if xml else ""]
                       for idx, name, cls, dim, xml in e.obs_rows]), "",
                "## Action space", "",
                f"The action has {f['action_dim']} dimensions, one per actuator, each in "
                f"[{fmt(f['action_low'])}, {fmt(f['action_high'])}]. {control_text(f)} Another "
                "[control function](../user_guide/control_functions.md) can be selected with `control_type`.", "",
                table(["Index", "Actuator", "Acts on", "Type", "Joint range", "Control range"],
                      [[k, f"`{name}`", target, kind, jr, ctrl] for k, name, target, kind, jr, ctrl in e.action_rows]),
                ""]

    out += ["## API", "", f"- {class_ref(e.cls)}"]
    if e.mjx_name:
        mjx_cls = loco_mujoco.get_registered_envs()[e.mjx_name]
        out += [f"- {class_ref(mjx_cls)}"]
    out += [""]
    return "\n".join(out)


def render_index(embodiments: List[Embodiment]) -> str:
    counts = {g: sum(e.group == g for e in embodiments) for g in GROUPS}
    out = [HEADER, "# Environments", "",
           f"LocoMuJoCo provides {len(embodiments)} embodiments: {counts['humanoid']} humanoid robots, "
           f"{counts['human']} (musculo-)skeletal human models and {counts['quadruped']} quadrupeds. Every "
           "embodiment is an environment class that is registered under its class name and created through a "
           "[task factory](../user_guide/task_factories.md). All of them share the same interface and the same "
           "pluggable observations, rewards, control functions, terrains and domain randomization.", "",
           "Each embodiment has a variant for GPU simulation, registered under the same name with the prefix "
           "`Mjx` (for example `MjxUnitreeG1`). It runs on MJX or MuJoCo Warp, see "
           "[backends](../user_guide/backends.md).", "",
           "```python",
           "import loco_mujoco",
           "",
           "print(list(loco_mujoco.get_registered_envs()))",
           "```", "",
           "## Overview", "",
           "DoF is the number of joint degrees of freedom without the six of the floating base, and actions is "
           "the dimension of the action space, both for the default arguments of the environment. The last "
           "column lists the [dataset sources](../user_guide/datasets.md) with motion capture data for the "
           "embodiment. The MJX variant of an embodiment is registered as `Mjx<registered name>`.", ""]

    rows = []
    for e in embodiments:
        dof = e.facts.get("n_dof", "n/a")
        act = e.facts.get("action_dim", "n/a")
        rows.append([f"[{e.meta['title']}]({e.meta['page']}.md)", f"`{e.name}`", GROUPS[e.group]["type_label"],
                     dof, act, "yes" if e.mjx_name else "no", datasets_text(e)])
    out += [table(["Embodiment", "Registered name", "Type", "DoF", "Actions", "MJX", "Datasets"], rows), ""]

    for group, info in GROUPS.items():
        members = [e for e in embodiments if e.group == group]
        if not members:
            continue
        out += [f"## {info['heading']}", "", GROUP_INTRO[group], "", "::::{grid} 2 3 4 4", ":gutter: 3", ""]
        for e in members:
            images = existing_images(e)
            out += [f":::{{grid-item-card}} {e.meta['title']}", ":class-card: lmj-env-card"]
            if images:
                out += [f":img-top: {IMG_REL}/{images[0]}", f":img-alt: {e.meta['title']}"]
            out += [f":link: {e.meta['page']}", ":link-type: doc", "", e.meta["tagline"], "+++"]
            if e.error:
                out += ["Model not installed"]
            else:
                out += [f"{e.facts['n_dof']} DoF · {e.facts['action_dim']} actions"]
            out += [":::", ""]
        out += ["::::", ""]

    out += ["## Adding your own", "",
            "A robot that is not in the list can be added from a package of your own, without changing "
            "LocoMuJoCo. [Adding a new robot](../user_guide/new_robot.md) describes the procedure, including "
            "how to make the motion capture datasets available for it.", ""]

    for group, info in GROUPS.items():
        members = [e for e in embodiments if e.group == group]
        if not members:
            continue
        out += ["```{toctree}", ":hidden:", f":caption: {info['caption']}", ""]
        out += [f"{e.meta['title']} <{e.meta['page']}>" for e in members]
        out += ["```", ""]
    return "\n".join(out)


def main() -> None:
    embodiments = collect_embodiments()
    for e in embodiments:
        print(f"[generate_environments] {e.name}")
        extract(e)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written = set()
    for e in embodiments:
        path = OUT_DIR / f"{e.meta['page']}.md"
        path.write_text(render_page(e))
        written.add(path.name)
    (OUT_DIR / "index.md").write_text(render_index(embodiments))
    written.add("index.md")

    # remove pages of embodiments that no longer exist (only files this script generated)
    for path in OUT_DIR.glob("*.md"):
        if path.name not in written and path.read_text().startswith(HEADER.splitlines()[0]):
            path.unlink()
            print(f"[generate_environments] removed stale page {path.name}")

    failed = [e.name for e in embodiments if e.error]
    print(f"[generate_environments] wrote {len(written)} files to {OUT_DIR}"
          + (f"; could not instantiate: {', '.join(failed)}" if failed else ""))


if __name__ == "__main__":
    main()
