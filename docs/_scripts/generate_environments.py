@dataclass
class Option:
    name: str
    default: str
    description: str
    effect: str = ""


@dataclass
class Embodiment:
    name: str
    cls: type
    group: str
    meta: Dict
    mjx_name: Optional[str] = None
    aliases: List[str] = field(default_factory=list)
    datasets: List[str] = field(default_factory=list)
    options: List[Option] = field(default_factory=list)
    mjx_timing: Optional[tuple] = None
    error: Optional[str] = None
    facts: Dict = field(default_factory=dict)
    obs_rows: List[tuple] = field(default_factory=list)
    action_rows: List[tuple] = field(default_factory=list)


def camel_to_snake(name: str) -> str:
    """Fallback page name for an embodiment without an entry in EMBODIMENTS."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).lower()


def fmt(x: float) -> str:
    """Formats a number with at most four significant digits."""
    if np.isinf(x):
        return "-inf" if x < 0 else "inf"
    s = f"{float(x):.4g}"
    return "0" if s in ("-0", "0") else s


def group_of(cls: type) -> str:
    if issubclass(cls, BaseRobotQuadruped):
        return "quadruped"
    if issubclass(cls, (BaseSkeleton, MyoSkeleton)):
        return "human"
    return "humanoid"


def collect_embodiments() -> List[Embodiment]:
    """Sorts the registry into embodiments, MJX variants and deprecated aliases."""
    registry = {name: cls for name, cls in loco_mujoco.get_registered_envs().items()
                if cls.__module__.startswith("loco_mujoco.")}

    cpu = {name: cls for name, cls in registry.items() if not getattr(cls, "mjx_enabled", False)}
    # an alias subclasses another registered CPU class directly and defines nothing but a constructor
    aliases = {}
    for name, cls in cpu.items():
        parent = cls.__mro__[1]
        own = {k for k in vars(cls) if not k.startswith("__")}
        if parent in cpu.values() and not own:
            aliases[name] = parent.__name__

    embodiments = []
    for name, cls in cpu.items():
        if name in aliases:
            continue
        meta = EMBODIMENTS.get(name)
        if meta is None:
            print(f"[generate_environments] WARNING: '{name}' has no entry in EMBODIMENTS, using fallbacks.")
            meta = dict(title=name, page=camel_to_snake(name), images=[], tagline=group_of(cls).capitalize(),
                        description=(inspect.getdoc(cls) or "").split("\n\n")[0])
        mjx_name = "Mjx" + name
        if not (mjx_name in registry and getattr(registry[mjx_name], "mjx_enabled", False)):
            mjx_name = None
        e = Embodiment(name=name, cls=cls, group=group_of(cls), meta=meta, mjx_name=mjx_name,
                       aliases=sorted(a for a, p in aliases.items() if p == name))
        if mjx_name:
            e.mjx_timing = mjx_timing(registry[mjx_name])
        e.datasets = datasets_of(name)
        embodiments.append(e)

    order = list(EMBODIMENTS)
    embodiments.sort(key=lambda e: (list(GROUPS).index(e.group),
                                    order.index(e.name) if e.name in order else len(order), e.name))
    for name in EMBODIMENTS:
        if name not in cpu:
            print(f"[generate_environments] WARNING: '{name}' is in EMBODIMENTS but not in the registry.")
    return embodiments


def datasets_of(name: str) -> List[str]:
    """Dataset sources of an embodiment: all three if it has a retargeting configuration, none otherwise."""
    conf = Path(loco_mujoco.PATH_TO_SMPL_ROBOT_CONF) / f"{name}.yaml"
    return list(DATASET_LABELS) if conf.is_file() else []


def mjx_timing(mjx_cls: type) -> Optional[tuple]:
    """Default (timestep, n_substeps) of an MJX class, read from its constructor signature."""
    params = inspect.signature(mjx_cls.__init__).parameters
    try:
        return float(params["timestep"].default), int(params["n_substeps"].default)
    except (KeyError, TypeError, ValueError):
        return None


def parse_args_doc(doc: str) -> Dict[str, str]:
    """Extracts the ``Args:`` section of a Google-style docstring as {name: description}."""
    out, current, in_args = {}, None, False
    for line in (doc or "").splitlines():
        stripped = line.strip()
        if stripped in ("Args:", "Arguments:"):
            in_args = True
            continue
        if not in_args:
            continue
        if re.match(r"^(Returns|Raises|Yields|Note|Example)s?:", stripped):
            break
        m = re.match(r"^(\*{0,2}\w+)\s*(\([^)]*\))?:\s*(.*)$", stripped)
        if m:
            current = m.group(1).lstrip("*")
            out[current] = m.group(3).strip()
        elif current and stripped:
            out[current] += " " + stripped
    return out


def rst_to_md(text: str) -> str:
    """Turns the reStructuredText inline markup of a docstring into Markdown that is safe in a table cell."""
    text = re.sub(r":\w+(?::\w+)?:`~?([^`]+)`", r"`\1`", text)   # roles such as :attr:`name`
    text = text.replace("``", "`")
    return text.replace("|", "\\|")


def constructor_options(cls: type) -> List[Option]:
    """The embodiment-specific constructor arguments, collected over the classes below ``LocoEnv``."""
    options = OrderedDict()
    for klass in cls.__mro__:
        if klass is LocoEnv:
            break
        init = vars(klass).get("__init__")
        if init is None:
            continue
        docs = parse_args_doc(inspect.getdoc(init))
        for pname, p in inspect.signature(init).parameters.items():
            if pname in COMMON_ARGS or pname in FIXED_ARGS or pname in options:
                continue
            if p.kind in (p.VAR_KEYWORD, p.VAR_POSITIONAL) or p.default is inspect.Parameter.empty:
                continue
            description = rst_to_md(docs.get(pname, ""))
            if description and not description.endswith("."):
                description += "."
            options[pname] = Option(pname, repr(p.default), description)

    source = "".join(inspect.getsource(k) for k in cls.__mro__ if k is not LocoEnv and issubclass(k, LocoEnv))
    for pname, info in KWARG_OPTIONS.items():
        if f'"{pname}"' in source:
            options[pname] = Option(pname, info["default"], info["description"])
    return list(options.values())


def make_env(cls: type, **kwargs):
    """Instantiates an environment quietly. Raises RuntimeError with a short reason on failure."""
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            return cls(print_obs_summary=False, **kwargs)
    except SystemExit:
        # MyoSkeleton calls exit() when its model has not been downloaded
        raise RuntimeError("the model files are not installed")
    except Exception as exc:  # noqa: BLE001
        raise RuntimeError(f"{type(exc).__name__}: {exc}")


def actuator_kind(model, index: int) -> str:
    if model.actuator_dyntype[index] == mujoco.mjtDyn.mjDYN_MUSCLE:
        return "muscle"
    if model.actuator_biastype[index] == mujoco.mjtBias.mjBIAS_AFFINE:
        return "position"
    return "torque"


def actuator_target(model, index: int) -> str:
    trntype, trnid = model.actuator_trntype[index], model.actuator_trnid[index][0]
    obj = {mujoco.mjtTrn.mjTRN_JOINT: mujoco.mjtObj.mjOBJ_JOINT,
           mujoco.mjtTrn.mjTRN_JOINTINPARENT: mujoco.mjtObj.mjOBJ_JOINT,
           mujoco.mjtTrn.mjTRN_TENDON: mujoco.mjtObj.mjOBJ_TENDON,
           mujoco.mjtTrn.mjTRN_SITE: mujoco.mjtObj.mjOBJ_SITE}.get(trntype)
    name = mujoco.mj_id2name(model, obj, trnid) if obj is not None else None
    label = {mujoco.mjtTrn.mjTRN_TENDON: "tendon ", mujoco.mjtTrn.mjTRN_SITE: "site "}.get(trntype, "")
    return f"{label}`{name}`" if name else ""


def joint_range(model, index: int) -> str:
    """The position range of the joint an actuator acts on, empty for other transmissions."""
    if model.actuator_trntype[index] != mujoco.mjtTrn.mjTRN_JOINT:
        return ""
    jid = model.actuator_trnid[index][0]
    if not model.jnt_limited[jid]:
        return "unlimited"
    low, high = model.jnt_range[jid]
    return f"[{fmt(low)}, {fmt(high)}]"


def control_text(f: Dict) -> str:
    """Describes how the default control function of an environment turns an action into actuator controls."""
    name = f["control_cls"].__name__
    ref = class_ref(f["control_cls"])
    if name == "DefaultControl":
        return (f"The default control type, {ref}, maps this interval linearly to the control range of each "
                "actuator, so an action is a normalized actuator command.")
    if name == "PDControl":
        if f["scale_to_jnt_limits"]:
            scale = "The action is scaled from [-1, 1] to the joint range first."
        else:
            scale = "The action is used as it is, in the unit of the joint, and is not scaled to the joint range."
        return (f"The default control type of this environment is {ref}: an action is a joint position target, "
                f"given as an offset from the nominal joint positions. {scale} The target is clipped to the joint "
                "range, and the torque of the PD controller is clipped to the control range of the actuator.")
    return f"The default control type is {ref}."


def extract(e: Embodiment) -> None:
    """Instantiates the embodiment and fills in its facts and tables."""
    e.options = constructor_options(e.cls)
    try:
        env = make_env(e.cls)
    except RuntimeError as exc:
        e.error = str(exc)
        print(f"[generate_environments] WARNING: could not instantiate {e.name}: {e.error}")
        return

    model = env._model
    n_free = int(np.sum(model.jnt_type == mujoco.mjtJoint.mjJNT_FREE))
    action_indices = [int(i) for i in np.asarray(env._action_indices)]
    kinds = [actuator_kind(model, i) for i in action_indices]
    kind_counts = OrderedDict((k, kinds.count(k)) for k in ("torque", "position", "muscle") if k in kinds)
    xml_path = Path(e.cls.get_default_xml_file_path())

    e.facts = dict(
        n_joints=int(model.njnt) - n_free,
        n_dof=int(model.nv) - 6 * n_free,
        nq=int(model.nq), nv=int(model.nv),
        n_actuators=int(model.nu),
        action_dim=int(env.info.action_space.shape[0]),
        obs_dim=int(env.info.observation_space.shape[0]),
        control_cls=type(env._control_func),
        timestep=float(model.opt.timestep),
        n_substeps=int(round(env.dt / model.opt.timestep)),
        dt=float(env.dt),
        n_eq=int(model.neq),
        kind_counts=kind_counts,
        model_file="/".join(xml_path.parts[-2:]),
        n_mimic_sites=len(getattr(env, "sites_for_mimic", [])),
        action_low=float(np.min(env.info.action_space.low)),
        action_high=float(np.max(env.info.action_space.high)),
        scale_to_jnt_limits=getattr(env._control_func, "_scale_action_to_jnt_limits", None),
    )

    for obs in env.obs_container.values():
        ind = np.asarray(obs.obs_ind)
        if ind.size == 0:
            continue
        idx = str(int(ind[0])) if ind.size == 1 else f"{int(ind[0])}–{int(ind[-1])}"
        e.obs_rows.append((idx, obs.name, type(obs), int(obs.dim), getattr(obs, "xml_name", None)))

    for k, i in enumerate(action_indices):
        name = mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_ACTUATOR, i)
        if model.actuator_ctrllimited[i]:
            low, high = model.actuator_ctrlrange[i]
            ctrl = f"[{fmt(low)}, {fmt(high)}]"
        else:
            ctrl = "unlimited"
        e.action_rows.append((k, name, actuator_target(model, i), kinds[k], joint_range(model, i), ctrl))

    # effect of the boolean options on the size of the spaces
    for opt in e.options:
        if opt.default not in ("True", "False") or opt.name in KWARG_OPTIONS:
            continue
        flipped = opt.default == "False"
        try:
            env2 = make_env(e.cls, **{opt.name: flipped})
        except RuntimeError:
            continue
        n_obs, n_act = int(env2.info.observation_space.shape[0]), int(env2.info.action_space.shape[0])
        if (n_obs, n_act) == (e.facts["obs_dim"], e.facts["action_dim"]):
            opt.effect = f"`{flipped}`: same spaces"
        else:
            opt.effect = f"`{flipped}`: {n_obs} observations, {n_act} actions"


