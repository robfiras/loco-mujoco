"""
Generates the environment gallery of the documentation.

The script enumerates the environments in the LocoMuJoCo registry (``loco_mujoco.get_registered_envs()``),
instantiates each embodiment once on the CPU (headless, nothing is rendered) and writes

- ``docs/environments/index.md``: the gallery with a summary table and one card per embodiment, and
- ``docs/environments/<embodiment>.md``: one page per embodiment with a quick-start snippet, a table of
  facts, the constructor options and the default observation and action space.

Everything that can be read from the code is read from the code: the number of joints and actuators, the
spaces, the time steps, the constructor options and their documentation, whether an MJX variant is
registered, and for which embodiments motion capture data exists. Only the descriptive text, the display
names and the image files are kept by hand, in ``EMBODIMENTS`` below.

How registered names are interpreted:

- ``Mjx<Name>`` is the MJX variant of ``<Name>``, not an embodiment of its own.
- A registered class that only subclasses another registered embodiment without changing it
  (``HumanoidTorque``, ``HumanoidMuscle``) is a deprecated alias and is listed on the page of its parent.
- Classes that are registered by other packages (for example the real-robot environments of
  LocoMuJoCo Real) are ignored; only classes defined in ``loco_mujoco`` are documented.

Motion capture data: the default dataset, LAFAN1 and AMASS are available for exactly those embodiments
that have a retargeting configuration in ``loco_mujoco/smpl/robot_confs/<Name>.yaml``, which is what
``ImitationFactory`` needs to load or retarget a clip. This is checked on the file system, not on the
Hugging Face hub, so the script needs no network access (apart from the one-time download of the robot
models).

Usage, from the repository root::

    python docs/_scripts/generate_environments.py

The output is deterministic. Rerun the script after adding an environment or changing a default
observation or action space, and commit the result. An environment that cannot be instantiated (for
example ``MyoSkeleton`` without its license-gated model) still gets a page, with a note instead of the
tables.
"""
